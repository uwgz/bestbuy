"""
Database connection handling and table setup.

On your computer: a SQLite file in instance/ (nothing to install).
Online: PostgreSQL on Neon, when DATABASE_URL is set to its connection string (see app/postgres.py).
The queries are written once and work on both.
"""
import re
import sqlite3
from datetime import datetime, timezone
from pathlib import Path

from flask import current_app, g

from . import postgres


def using_postgres(app=None):
    return postgres.is_postgres_url((app or current_app).config.get("DATABASE_URL"))


def now_text():
    """Current time (UTC) as stored in the created_at / updated_at columns."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S")


def get_db():
    """One connection per request, rows behave like dicts."""
    if "db" not in g:
        if using_postgres():
            g.db = postgres.connect(current_app.config["DATABASE_URL"], current_app.config)
        else:
            g.db = sqlite3.connect(current_app.config["DATABASE"])
            g.db.row_factory = sqlite3.Row
            g.db.execute("PRAGMA foreign_keys = ON")
    return g.db


def close_db(exc=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def query(sql, args=(), one=False):
    rows = get_db().execute(sql, args).fetchall()
    return (rows[0] if rows else None) if one else rows


def execute(sql, args=()):
    db = get_db()
    cur = db.execute(sql, args)
    db.commit()
    return cur.lastrowid


def init_schema():
    schema = (Path(__file__).parent / "schema.sql").read_text()
    if using_postgres():
        schema = postgres_schema(schema)
    db = get_db()
    db.executescript(schema)
    db.commit()


def postgres_schema(sql):
    """schema.sql is written for SQLite; these few changes make it PostgreSQL."""
    sql = re.sub(r"PRAGMA[^;]*;", "", sql)
    sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    sql = sql.replace(" COLLATE NOCASE", "")                      # emails are stored in lower case
    sql = sql.replace("DEFAULT (datetime('now'))",
                      "DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'))")
    sql = sql.replace("DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))",
                      """DEFAULT (to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'))""")
    return sql


def init_app(app):
    app.teardown_appcontext(close_db)
    # Create the tables on first start (safe to run every time). The site starts empty:
    # products, services, gear and photos are added from the admin panel.
    with app.app_context():
        init_schema()
